/// One downloadable file of a model, pinned by size and SHA-256.
@immutable
class ModelFile {
  const ModelFile({required this.name, required this.bytes, required this.sha256});

  factory ModelFile.fromJson(Map<String, Object?> json) => ModelFile(
        name: json['name']! as String,
        bytes: json['bytes']! as int,
        sha256: json['sha256']! as String,
      );

  final String name;
  final int bytes;
  final String sha256;
}

/// Something that can be downloaded: a speech model, a voice, or the voice data.
abstract class Downloadable {
  String get id;
  List<ModelFile> get files;
  int get totalBytes => files.fold(0, (sum, f) => sum + f.bytes);
}

@immutable
class RecognizerModel extends Downloadable {
  RecognizerModel.fromJson(Map<String, Object?> json)
      : id = json['id']! as String,
        size = RecognizerSize.values.byName(json['size']! as String),
        name = json['name']! as String,
        license = json['license']! as String,
        encoder = ModelFile.fromJson((json['encoder']! as Map).cast()),
        decoder = ModelFile.fromJson((json['decoder']! as Map).cast()),
        tokens = ModelFile.fromJson((json['tokens']! as Map).cast());

  @override
  final String id;
  final RecognizerSize size;
  final String name;
  final String license;
  final ModelFile encoder;
  final ModelFile decoder;
  final ModelFile tokens;

  @override
  List<ModelFile> get files => [encoder, decoder, tokens];
}

@immutable
class VoiceModel extends Downloadable {
  VoiceModel.fromJson(Map<String, Object?> json)
      : id = json['id']! as String,
        name = json['name']! as String,
        language = json['language']! as String,
        locale = json['locale']! as String,
        gender = json['gender']! as String,
        license = json['license']! as String,
        model = ModelFile.fromJson((json['model']! as Map).cast()),
        tokens = ModelFile.fromJson((json['tokens']! as Map).cast()),
        modelCard = ModelFile.fromJson((json['modelCard']! as Map).cast());

  @override
  final String id;
  final String name;
  final String language;
  final String locale;
  final String gender;
  final String license;
  final ModelFile model;
  final ModelFile tokens;
  final ModelFile modelCard;

  @override
  List<ModelFile> get files => [model, tokens, modelCard];
}

/// The eSpeak NG data every natural voice needs, downloaded once as a zip.
@immutable
class VoiceData extends Downloadable {
  VoiceData.fromJson(Map<String, Object?> json)
      : id = json['id']! as String,
        license = json['license']! as String,
        archive = ModelFile.fromJson((json['archive']! as Map).cast());

  @override
  final String id;
  final String license;
  final ModelFile archive;

  @override
  List<ModelFile> get files => [archive];
}

/// `assets/models/catalog.json`, generated by `tool/models/build_models.py`.
@immutable
class ModelCatalog {
  ModelCatalog.fromJson(Map<String, Object?> json)
      : release = json['release']! as String,
        baseUrl = json['baseUrl']! as String,
        recognizers = [
          for (final r in json['recognizers']! as List) RecognizerModel.fromJson((r as Map).cast()),
        ],
        voiceData = json['voiceData'] == null ? null : VoiceData.fromJson((json['voiceData']! as Map).cast()),
        voices = [for (final v in json['voices']! as List) VoiceModel.fromJson((v as Map).cast())];

  static const asset = 'assets/models/catalog.json';

  static Future<ModelCatalog> load([AssetBundle? bundle]) async =>
      ModelCatalog.fromJson((jsonDecode(await (bundle ?? rootBundle).loadString(asset)) as Map).cast());

  final String release;
  final String baseUrl;
  final List<RecognizerModel> recognizers;
  final VoiceData? voiceData;
  final List<VoiceModel> voices;

  RecognizerModel recognizer(RecognizerSize size) =>
      recognizers.firstWhere((r) => r.size == size, orElse: () => recognizers.first);

  VoiceModel? voice(String id) {
    for (final v in voices) {
      if (v.id == id) return v;
    }
    return null;
  }

  List<VoiceModel> voicesFor(String language) => voices.where((v) => v.language == language).toList();

  Uri urlFor(ModelFile file) => Uri.parse('$baseUrl${file.name}');
}
